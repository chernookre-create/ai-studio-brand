def добавить(номер, класс, место, описание, проверка=None, статус='не разобрана'):
    """Завести находку. Если такой отпечаток уже закрывали — это рецидив, и он именной."""
    d = прочитать()
    новая = {'номер': номер, 'класс': класс, 'место': место, 'описание': описание,
             'проверка': проверка, 'статус': статус, 'рецидивПосле': None}
    о = отпечаток(новая)
    прежние = [f for f in d['находки'].values()
               if отпечаток(f) == о and f['номер'] != номер]
    закрытые = [f for f in прежние if f['статус'] == 'закрыта']
    if закрытые:
        новая['рецидивПосле'] = [f['номер'] for f in закрытые]
    d['находки'][номер] = новая
    d['история'].append({'что': 'добавлена', 'номер': номер, 'отпечаток': о})
    записать(d)
    return новая


def закрыть(номер, проверкой):
    """Закрыть находку. Без имени проверки — нельзя, и это единственное жёсткое правило."""
    d = прочитать()
    if номер not in d['находки']:
        raise KeyError(f'{номер}: такой находки в реестре нет')
    if not проверкой:
        raise ValueError(f'{номер}: закрыть без проверки нельзя — назови ту, что на ней падает')
    f = d['находки'][номер]
    f['проверка'] = проверкой
    f['статус'] = 'закрыта'
    d['история'].append({'что': 'закрыта', 'номер': номер, 'проверкой': проверкой})
    записать(d)
    return f


def рецидивы():
    d = прочитать()
    return [f for f in d['находки'].values() if f.get('рецидивПосле')]


def по_классам():
    d = прочитать()
    итог = {}
    for f in d['находки'].values():
        c = итог.setdefault(f.get('класс', 'прочее'), {'всего': 0, 'открыто': 0, 'закрыто': 0})
        c['всего'] += 1
        c['закрыто' if f['статус'] == 'закрыта' else 'открыто'] += 1
    return итог


def незакрытые():
    d = прочитать()
    return [f for f in d['находки'].values() if f['статус'] != 'закрыта']


