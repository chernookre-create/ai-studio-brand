def _пусто():
    return {'схема': 1, 'находки': {}, 'история': []}


def прочитать():
    try:
        d = json.load(open(РЕЕСТР, encoding='utf-8'))
        return {**_пусто(), **d}
    except Exception:                                            # noqa: BLE001
        return _пусто()


def записать(d):
    os.makedirs(os.path.dirname(РЕЕСТР), exist_ok=True)
    врем = РЕЕСТР + '.tmp'
    with open(врем, 'w', encoding='utf-8') as f:
        json.dump(d, f, ensure_ascii=False, indent=1)
        f.flush()
        os.fsync(f.fileno())
    os.replace(врем, РЕЕСТР)


def отпечаток(находка):
    """Что делает две находки одной и той же. Не текст описания — он каждый раз новый."""
    место = (находка.get('место') or '').strip().lower()
    return f"{находка.get('класс', 'прочее')}|{место}"


