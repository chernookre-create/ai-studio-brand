def отчёт():
    без, ложно, закрыто = аудит()
    d = прочитать()
    всего = len(d['находки'])
    рец = рецидивы()
    print('\nУЧЁТ НАХОДОК — почему проект ещё не закончен')
    print('=' * 70)
    неразобранные = [f for f in без if f['статус'] == 'не разобрана']
    нужна = [f for f in без if f['статус'] == 'нужна проверка']
    законы = [f for f in d['находки'].values() if f['статус'] == 'не требует проверки']
    print(f'\nВсего находок в реестре: {всего}')
    print(f'  удержано живой проверкой:     {len(закрыто)}')
    print(f'  стало законом, проверки нет:  {len(законы)}')
    print(f'  ЗАКРЫТО ССЫЛКОЙ НА ПУСТОТУ:   {len(ложно)}')
    print(f'  known дефект без проверки:    {len(нужна)}')
    print(f'  ещё не разобрано:             {len(неразобранные)}')
    сумма = len(закрыто) + len(законы) + len(ложно) + len(нужна) + len(неразобранные)
    if сумма != всего:
        чужие = sorted({f['статус'] for f in d['находки'].values()}
                       - {'закрыта', 'заявлена закрытой', 'не требует проверки',
                          'нужна проверка', 'не разобрана'})
        print(f'\n  СЧЁТ НЕ СХОДИТСЯ: по стопкам {сумма}, всего {всего}. '
              f'Статусы вне словаря: {", ".join(чужие) or "нет"}')
        print('  Находка, не попавшая ни в одну стопку, не видна ни одному отчёту.')
    print(f'\nЖивых пунктов проверок сейчас: {len(живые_проверки())} — '
          + ', '.join(sorted(живые_проверки())))

    if ложно:
        print('\nЗАКРЫТО ССЫЛКОЙ НА ПУНКТ, КОТОРОГО НЕТ — это «закрыто» без основания:')
        for f in ложно[:10]:
            print(f'  {f["номер"]}: проверка «{f["проверка"]}» в отчёте не печатается')

    if рец:
        print('\nРЕЦИДИВЫ — вернулось после «закрыто»:')
        for f in рец:
            print(f'  {f["номер"]} ← {", ".join(f["рецидивПосле"])}  ({f["место"]})')

    print('\nЧТО МЕШАЕТ ЗАКОНЧИТЬ')
    if not нужна and not ложно and not неразобранные:
        print('  Ничего: у каждой находки либо живая проверка, либо явное решение человека,')
        print('  что проверять нечего. Круг закрыт.')
    else:
        if ложно:
            print(f'  {len(ложно)} находок «закрыты» ссылкой на пункт, которого нет. Это худший')
            print('  случай: мы думаем, что удержали, а не удержали.')
        if нужна:
            print(f'  {len(нужна)} дефектов без проверки. Каждый вернётся — как уже было пять раз.')
        if неразобранные:
            print(f'  {len(неразобранные)} записей не разобрано: неизвестно, дефект это или')
            print('  открытие о модели. Разбирать по месту, а не по одной: у находок одного')
            print('  места одна проверка. Разбор — решение человека, машина его не угадывает.')
    print('=' * 70 + '\n')
    return 1 if ложно else 0


def main():
    a = sys.argv[1:]
    if '--пересобрать' in a:
        r, e = пересобрать()
        if e:
            print(e)
        else:
            print(f'из журнала заведено новых: {r["новых"]}, всего в реестре: {r["всего"]}')
            if r['непонятые']:
                print('\nВ журнале упомянуты, но заголовком не оформлены — разнеси руками')
                print('или убедись, что номер свободен:')
                print('  ' + ', '.join(r['непонятые']))
        return 0 if r else 1
    if '--рецидивы' in a:
        r = рецидивы()
        if not r:
            print('рецидивов нет: ни одна закрытая находка не вернулась')
            return 0
        for f in r:
            print(f'{f["номер"]} ← вернулась после {", ".join(f["рецидивПосле"])}: {f["описание"]}')
        return 1
    if '--закрыть' in a:
        i = a.index('--закрыть')
        номер = a[i + 1] if i + 1 < len(a) else None
        проверкой = a[a.index('--проверкой') + 1] if '--проверкой' in a else None
        if not номер or not проверкой:
            print('нужно: --закрыть ФN --проверкой <пункт>\n'
                  'Закрыть без проверки нельзя: это и есть выход из круга.')
            return 2
        if проверкой not in живые_проверки():
            print(f'пункта «{проверкой}» в отчёте нет. Сначала заведи проверку, потом закрывай.')
            return 2
        f = закрыть(номер, проверкой)
        print(f'{f["номер"]} закрыта проверкой {проверкой}')
        return 0
    if '--добавить' in a:
        i = a.index('--добавить')
        try:
            номер, класс, место, описание = a[i + 1], a[i + 2], a[i + 3], a[i + 4]
        except IndexError:
            print('нужно: --добавить ФN <класс> <место> "<описание>"')
            print('классы: ' + ', '.join(КЛАССЫ))
            return 2
        f = добавить(номер, класс, место, описание)
        print(f'{f["номер"]} заведена' + (f'  ← РЕЦИДИВ после {f["рецидивПосле"]}'
                                          if f['рецидивПосле'] else ''))
        return 0
    return отчёт()


