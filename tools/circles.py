ПУНКТЫ_ПРОВЕРОК = None


def живые_проверки():
    """Какие пункты проверок реально существуют — по отчёту, а не по списку в голове.

    Единственный способ отличить «закрыто проверкой 6к» от «написано, что закрыто». Если
    пункта нет в отчёте, ссылка на него — такое же «закрыто» без основания, как Ф115.
    """
    global ПУНКТЫ_ПРОВЕРОК
    if ПУНКТЫ_ПРОВЕРОК is not None:
        return ПУНКТЫ_ПРОВЕРОК
    import subprocess
    найдено = set()
    for скрипт in ('selftest.py', 'rules_selftest.py'):
        путь = os.path.join(ROOT, 'tools', скрипт)
        if not os.path.exists(путь):
            continue
        try:
            r = subprocess.run([sys.executable, путь], capture_output=True, text=True, timeout=1800)
        except Exception:                                        # noqa: BLE001
            continue
        for стр in (r.stdout or '').splitlines():
            m = re.match(r'^(\d+[а-яё]?)\.\s', стр.strip())
            if m:
                найдено.add(m.group(1))
        if скрипт == 'rules_selftest.py' and 'ПРОШЛО' in (r.stdout or ''):
            найдено.add('5б')
    ПУНКТЫ_ПРОВЕРОК = найдено
    return найдено


def пересобрать(путь_журнала=None):
    """Перечитать журнал и завести находки номерами и заголовками — без угадывания класса.

    Класс и место НЕ выводятся из текста. Пробовал: 92 записи из 110 попали бы в «прочее», а
    места вышли обрывками фраз. Это ровно та ошибка, которую проект запрещает — величина,
    посчитанная по косвенным признакам (F7). Класс ставит тот, кто работает с находкой.
    """
    путь = путь_журнала or os.path.join(ROOT, '00_obs', 'журнал.md')
    if not os.path.exists(путь):
        return None, f'нет файла {os.path.relpath(путь, ROOT)} — реестр не наполнен'
    текст = open(путь, encoding='utf-8').read()
    записи = {}
    # Заголовок ищется от начала строки. Без якоря finditer шёл слева направо без
    # перекрытий, и жирные слова внутри абзацев съедали открывающие звёздочки следующего
    # заголовка: две записи журнала так и не завелись, а разбор молчал. Чинить надо было
    # не регулярку заголовка, а место, откуда её пускают.
    # В теле заголовка звёздочек быть не может. Без этого запрета заголовок вида
    # «**ФN.**», где закрытие стоит сразу за точкой, не закрывался здесь вовсе — и
    # совпадение тянулось до звёздочек следующего заголовка, проглатывая его целиком.
    # Так молча терялись записи, идущие сразу за заголовками второго вида.
    for m in re.finditer(r'^\*\*Ф(\d+)\.\s*([^*]{5,200}?)\*\*', текст, re.S | re.M):
        записи[f'Ф{m.group(1)}'] = ' '.join(m.group(2).split())
    for m in re.finditer(r'\| Ф(\d+) \| ([^|]+)\|', текст):
        записи.setdefault(f'Ф{m.group(1)}', ' '.join(m.group(2).split()))
    # Третий вид: сцепленный заголовок — «ФN → ФM», «ФN, ФK», «ФN–ФM». Одна запись на
    # несколько номеров. Разносить их нельзя: какой факт какому номеру принадлежит, в
    # тексте не сказано, и разложить — значит посчитать величину по косвенным признакам.
    # Но и пропускать нельзя: номер занят в журнале и пуст в реестре, а это щель, из
    # которой лезет повторное занятие номера. Поэтому все номера заголовка заводятся с
    # одним общим описанием, и это прямо написано в самом описании — читающий видит, что
    # запись общая, а не потерянная.
    #
    # Тире между номерами значит диапазон, запятая и стрелка — перечисление.
    for m in re.finditer(r'^\*\*((?:Ф\d+\s*[,→–—-]\s*)+Ф\d+)\s*(?:\([^)]*\))?\.\*{0,2}'
                         r'\s*(.{5,200}?)(?:\.\s|\*\*|\n)', текст, re.M):
        голова, хвост_ = m.group(1), ' '.join(m.group(2).split())
        числа = [int(x) for x in re.findall(r'Ф(\d+)', голова)]
        диапазон = bool(re.search(r'\d\s*[–—-]\s*Ф', голова))
        номера = range(числа[0], числа[-1] + 1) if диапазон and len(числа) == 2 else числа
        общее = f'[сцеплено: {голова}] {хвост_}'
        for ч in номера:
            записи.setdefault(f'Ф{ч}', общее[:200])

    # Второй вид заголовка: жирным только номер, текст обычный — «**ФN.** Заголовок».
    # Первый вид, где жирное покрывает и заголовок, разбор знал; этот пропускал молча,
    # потому что искал закрывающие звёздочки не ближе пяти знаков, а здесь они стоят
    # сразу за точкой. 19.08 в журнале так оформлено четырнадцать записей, семь из них
    # в реестр не попали — и выглядело это как «журнал разобран целиком».
    for m in re.finditer(r'^\*\*Ф(\d+)\.\*\*\s*(.{5,200}?)(?:\.\s|\n)', текст, re.M):
        записи.setdefault(f'Ф{m.group(1)}', ' '.join(m.group(2).split()))

    d = прочитать()
    новых = 0
    for номер, заголовок in sorted(записи.items(), key=lambda x: int(x[0][1:])):
        if номер in d['находки']:
            continue
        # Заявленная проверка — это ЦИТАТА из журнала, а не догадка: текст либо называет
        # пункт («проверка 6ж», «пунктом 6б»), либо не называет. Существует ли названный
        # пункт на самом деле — выясняет аудит, и это разные утверждения (Ф115).
        хвост = текст[текст.index(f'Ф{номер[1:]}.'):][:1600] if f'Ф{номер[1:]}.' in текст else ''
        м = re.search(r'[Пп]роверк\w*\s+\*{0,2}`?(\d+[а-яё]?)`?|пунктом\s+\*{0,2}`?(\d+[а-яё]?)`?',
                      хвост)
        заявлена = (м.group(1) or м.group(2)) if м else None
        d['находки'][номер] = {'номер': номер, 'класс': None, 'место': None,
                               'описание': заголовок[:200], 'проверка': заявлена,
                               'статус': 'заявлена закрытой' if заявлена else 'не разобрана',
                               'рецидивПосле': None}
        новых += 1
    # Сцепленные заголовки — «ФN → ФM», «ФN, ФK», «ФN–ФM» — разбор не разносит: у
    # нескольких находок один текст, и какой кусок чей, машина не знает. Молча
    # пропустить их нельзя: номер остаётся занятым в журнале и пустым в реестре, а
    # это ровно та щель, из которой лезут повторные занятия номеров. Поэтому они
    # не угадываются, а называются человеку.
    все_номера = {f'Ф{m.group(1)}' for m in re.finditer(r'Ф(\d+)(?!\d)', текст)}
    непонятые = sorted(все_номера - set(записи) - set(d['находки']),
                       key=lambda x: int(x[1:]))
    d['история'].append({'что': 'пересобран из журнала', 'новых': новых})
    записать(d)
    return {'новых': новых, 'всего': len(d['находки']), 'непонятые': непонятые}, ''


def аудит():
    """Для каждой находки — есть ли у неё живая проверка.

    Три списка, и первые два обязаны стремиться к нулю:
      без_проверки — закрыть нечем, вернётся;
      ложно        — назван пункт, которого в отчёте нет;
      закрыто      — названный пункт существует.
    """
    d = прочитать()
    живые = живые_проверки()
    без_проверки, ложно, закрыто = [], [], []
    for f in d['находки'].values():
        if f['статус'] in ('закрыта', 'заявлена закрытой') and f.get('проверка'):
            (закрыто if f['проверка'] in живые else ложно).append(f)
        else:
            без_проверки.append(f)
    return без_проверки, ложно, закрыто


