#!/usr/bin/env python3
"""Учёт находок: почему проект ходит по кругу и когда он закончится.

    python3 tools/circles.py                  сколько осталось и что мешает закончить
    python3 tools/circles.py --рецидивы       что вернулось после «закрыто»
    python3 tools/circles.py --добавить ...   завести находку
    python3 tools/circles.py --закрыть Ф164 --проверкой 6б
    python3 tools/circles.py --пересобрать    перечитать журнал проекта

Зачем именно так. Круги здесь не в рантайме — скрипты запускаются секунды и завершаются.
Круг выглядит иначе: находка объявлена закрытой, следующая чистая сессия находит её снова.
За сутки это случилось пять раз подряд с одним и тем же классом — «правка, применённая не
везде» (Ф129 → Ф144 → Ф152 → Ф156 → Ф162), и каждый раз она объявлялась исправленной.

Отсюда единственное правило этого файла:

    ЗАКРЫТЬ НАХОДКУ МОЖНО ТОЛЬКО ПРОВЕРКОЙ, КОТОРАЯ НА НЕЙ ПАДАЕТ.

Не «я исправил», не «записано в журнал», а имя проверки, которую сломали нарочно и убедились,
что она это заметила. Находка без такой проверки остаётся открытой, сколько бы раз её ни
чинили. Это и есть выход из круга: круг существует ровно потому, что «исправлено» и
«больше не повторится» — разные утверждения, а мы их путали.

Второе следствие: у проекта появляется число, которое обязано убывать. Пока оно не ноль,
проект не закончен, и видно, что именно мешает.
"""
