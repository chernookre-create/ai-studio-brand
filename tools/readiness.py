# Пересчёт готовности в вероятность попасть в результат с первого раза.
# Шкала откалибрована по истории этого проекта: см. 00_readiness/READINESS.md.
# Готовность считает, сколько признаков задано. Вероятность попадания зависит ещё и от КЛАССА
# кадра — это выяснилось 13.08.2026, когда при 100% готовности заказчик принял 3 кадра из 11.
CLASS_HIT = {
    'референс': (80, 'один проход nano_banana_pro на наборе из девяти картинок — основной способ'),
    'правка': (75, 'правка утверждённого кадра без смены ракурса: замена изделия, кроп'),
    'ракурс': (60, 'смена ракурса правкой кадра; три четверти редактором — 0 из 1'),
    'новая': (15, 'новая генерация персоны в Soul 2 — схема отменена 17.08, для серии не годится'),
}


def probability(score, cls='база'):
    base, _ = CLASS_HIT[cls]
    if score >= 95:
        return base
    if score >= 85:
        return int(base * 0.8)
    if score >= 70:
        return int(base * 0.6)
    return int(base * 0.3)


def main():
    state = json.load(open('00_readiness/state.json', encoding='utf-8'))
    done = set(state.get('готово', []))
    if '--нет' in sys.argv:
        done -= set(sys.argv[sys.argv.index('--нет') + 1:])

    total = sum(w for _, w, _, _ in ITEMS)
    score = sum(w for i, w, _, _ in ITEMS if i in done)
    missing = [(i, w, t, r) for i, w, t, r in ITEMS if i not in done]

    pct = score / total * 100
    print(f"\nГотовность входных данных: {score}/{total} = {round(pct)}%")
    print("Вероятность попасть с первого раза — по классу кадра:")
    for cls, (_, note) in CLASS_HIT.items():
        print(f"    {cls:<8} около {probability(pct, cls):>3}%   — {note}")
    print()

    if not missing:
        print("Всё закрыто. Можно снимать.\n")
        return
    print("Не закрыто — и что из-за этого выйдет:\n")
    for i, w, t, r in sorted(missing, key=lambda x: -x[1]):
        print(f"  [{i}] −{w}%  {t}")
        print(f"        риск: {r}")
    print(f"\nЕсли снимать как есть, дороже всего обойдётся: "
          f"{max(missing, key=lambda x: x[1])[0]}.\n")


if __name__ == '__main__':
    main()
