"""Проверки инфраструктуры: автоотправка, .gitignore, сдача.

Заведён 19.08.2026. Пять находок — Ф135, Ф158, Ф181, Ф142, Ф137 — были исправлены
в коде и висели в статусе «заявлена закрытой»: правка есть, проверки нет.
По закону проекта это не закрытие.

Первая же проверка нашла живой дефект: launchd запускал старую копию sync.sh,
исправление Ф135 лежало в комплекте и никогда не выполнялось. Восьмой случай
класса «правка-не-везде» — и он прошёл мимо всех девятнадцати пунктов selftest,
потому что ни один не смотрел за границу репозитория.

Каждая проверка обязана уметь покраснеть на своей поломке. Как её ломать —
написано в комментарии рядом.
"""
import json
import os
import plistlib
import shutil
import subprocess
import sys
import tempfile

КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
сбои = []


def отметка(имя, ок, деталь=''):
    print(f"  {'OK  ' if ок else 'СБОЙ'}  {имя}" + (f' · {деталь}' if деталь else ''))
    if not ок:
        сбои.append(имя)


def гит_игнор(путь):
    """Судит ли .gitignore этот путь.

    --no-index обязателен. Без него check-ignore смотрит в индекс и на любой
    отслеживаемый файл отвечает «не игнорируется», каким бы ни было правило.
    Проверка на таком файле зелёная всегда и не краснеет ни на какой поломке —
    ровно тот дефект, который в проекте называется «проверка, которая
    срабатывает всегда» (Ф61). Поймано при попытке сломать её нарочно.
    """
    r = subprocess.run(['git', 'check-ignore', '--no-index', '-q', путь],
                       cwd=КОРЕНЬ, capture_output=True, text=True)
    return r.returncode == 0


# --- 1. Автоотправка выполняется тем же файлом, что лежит в комплекте (Ф135) -------
# Ломается так: изменить automation/sync.sh, не разворачивая, — проверка краснеет.
def проверка_автоотправки():
    plist = os.path.expanduser('~/Library/LaunchAgents/com.aistudio.autosync.plist')
    свой = os.path.join(КОРЕНЬ, 'automation', 'sync.sh')
    if not os.path.exists(plist):
        # Не «пропущено молча»: на чужой машине автоотправки нет, и это законно.
        отметка('автоотправка не развёрнута на этой машине — сверять не с чем', True)
        return
    with open(plist, 'rb') as f:
        арг = plistlib.load(f).get('ProgramArguments', [])
    пути = [os.path.expandvars(a.strip('"')) for a in арг if a.strip('"').endswith('.sh')]
    if not пути:
        отметка('в plist автоотправки не найден путь к скрипту', False, ' '.join(арг))
        return
    развёрнутый = пути[0]
    if not os.path.exists(развёрнутый):
        отметка('скрипт, который запускает launchd, отсутствует', False, развёрнутый)
        return
    одинаковы = open(развёрнутый, 'rb').read() == open(свой, 'rb').read()
    отметка('launchd запускает ровно тот скрипт, что лежит в комплекте', одинаковы,
          '' if одинаковы else f'{развёрнутый} разошёлся с automation/sync.sh')


# --- 2. .gitignore глушит каталоги, а не расширение (Ф158) -------------------------
# Ломается так: вернуть в .gitignore строку `*.png` — картинки набора станут
# игнорируемыми, и проверка покраснеет.
def проверка_гитигнора_картинок():
    # Путь нарочно несуществующий: check-ignore судит по правилу, а не по файлу.
    # Именно png — Ф158 была про `*.png`, и проверка на .jpg её поломку не заметит.
    едет = 'refs/проба_слота.png'
    не_едет = '05_deliver/проба.png'
    заглушен_едет, заглушен_не_едет = гит_игнор(едет), гит_игнор(не_едет)
    отметка('картинки набора не заглушены', not заглушен_едет,
          '' if not заглушен_едет else f'{едет} игнорируется — это Ф158')
    отметка('кадры сдачи заглушены', заглушен_не_едет,
          '' if заглушен_не_едет else f'{не_едет} уехал бы в публичный репозиторий')


# --- 3. Транзит заглушен якорно, комплект остаётся (Ф181) --------------------------
# Ломается так: убрать ведущий слеш у `/_снято_с_учёта/` — заглушится и папка
# внутри refs/, которая часть комплекта, и вторая проверка покраснеет.
def проверка_транзита():
    транзит = '_снято_с_учёта/проба.txt'
    комплект = 'refs/_снято_с_учёта/ЧТО_ЗДЕСЬ.md'
    заглушен_транзит, заглушен_комплект = гит_игнор(транзит), гит_игнор(комплект)
    отметка('транзитные папки моста заглушены', заглушен_транзит,
          '' if заглушен_транзит else 'транзит попадёт в коммит — это Ф181')
    отметка('refs/_снято_с_учёта остаётся в комплекте', not заглушен_комплект,
          '' if not заглушен_комплект else 'заглушено имя каталога вместо пути — это Ф158')


def _проба_кадров(куда):
    """Папка «скачанных кадров» с одним настоящим jpg и meta.json рядом."""
    # Картинка берётся из набора текущей съёмки, а не по зашитому имени: имена
    # съёмки в коде — это закон 6б, и selftest ловит их отдельным пунктом.
    with open(os.path.join(КОРЕНЬ, 'refs', 'CURRENT.json'), encoding='utf-8') as f:
        слоты = json.load(f)['слоты']
    исходник = os.path.join(КОРЕНЬ, слоты[sorted(слоты)[0]])
    shutil.copy(исходник, os.path.join(куда, 'проба.jpg'))
    meta = {'проба.jpg': {'код': 'T01', 'название': 'проба инфратеста', 'лицо': '0.700',
                          'узор': '0%', 'счёт': 'проба', 'вердикт': 'ок'}}
    with open(os.path.join(куда, 'meta.json'), 'w', encoding='utf-8') as f:
        json.dump(meta, f, ensure_ascii=False)


def _сдача(имя, src, env=None):
    return subprocess.run([sys.executable, 'tools/deliver.py', имя, src],
                          cwd=КОРЕНЬ, capture_output=True, text=True, env=env)


# --- 4. Повторная сдача не стирает предыдущую (Ф142) -------------------------------
# Ломается так: вернуть безусловный shutil.rmtree(out) в начало build() —
# файл заказчика исчезнет, и проверка покраснеет.
def проверка_повторной_сдачи():
    имя = '_инфратест'
    пути = [f'05_deliver/{имя}', f'05_deliver/{имя}-2']
    for п in пути:
        shutil.rmtree(os.path.join(КОРЕНЬ, п), ignore_errors=True)
        shutil.rmtree(os.path.join(КОРЕНЬ, п + '.zip'), ignore_errors=True)
    try:
        with tempfile.TemporaryDirectory() as src:
            _проба_кадров(src)
            r = _сдача(имя, src)
            папка = os.path.join(КОРЕНЬ, пути[0])
            # Судим по итоговому файлу, а не по наличию папки: папку build() создаёт
            # в начале, и при падении на середине она остаётся пустой. Первая
            # редакция этой проверки смотрела на папку и была зелёной на сдаче,
            # которая падала на шрифтах (Ф183). Проверка, зелёная на сломанном, —
            # это не проверка.
            собралась = os.path.exists(os.path.join(папка, 'ЗАМЕРЫ.csv'))
            if not собралась:
                отметка('первая сдача собралась', False, (r.stdout + r.stderr)[-300:])
                return
            # То, что заказчик мог положить в папку сдачи.
            метка = os.path.join(папка, 'файл-заказчика.txt')
            open(метка, 'w').write('не стирать')
            _сдача(имя, src)
            отметка('повторная сдача не стёрла предыдущую', os.path.exists(метка),
                  '' if os.path.exists(метка) else 'файл заказчика исчез — это Ф142')
            отметка('повторная сдача собралась рядом', os.path.isdir(os.path.join(КОРЕНЬ, пути[1])),
                  '' if os.path.isdir(os.path.join(КОРЕНЬ, пути[1])) else 'папки -2 нет')
    finally:
        for п in пути:
            shutil.rmtree(os.path.join(КОРЕНЬ, п), ignore_errors=True)
            if os.path.exists(os.path.join(КОРЕНЬ, п + '.zip')):
                os.remove(os.path.join(КОРЕНЬ, п + '.zip'))


# --- 5. Несобравшийся архив замечен (Ф137) ----------------------------------------
# Ломается так: убрать проверку `code != 0` — скрипт напечатает успех при мёртвом
# zip, и проверка покраснеет.
def проверка_архива():
    имя = '_инфратест-zip'
    путь = os.path.join(КОРЕНЬ, f'05_deliver/{имя}')
    shutil.rmtree(путь, ignore_errors=True)
    try:
        with tempfile.TemporaryDirectory() as src, tempfile.TemporaryDirectory() as bin_:
            _проба_кадров(src)
            # Подсадной zip, который всегда падает: настоящий из системы не удаляем.
            фальшивый = os.path.join(bin_, 'zip')
            open(фальшивый, 'w').write('#!/bin/sh\nexit 1\n')
            os.chmod(фальшивый, 0o755)
            env = dict(os.environ, PATH=bin_ + os.pathsep + os.environ.get('PATH', ''))
            r = _сдача(имя, src, env=env)
            вывод = r.stdout + r.stderr
            заметил = 'архив не собран' in вывод
            соврал = '.zip — кадров' in вывод
            отметка('провал архивации замечен', заметил and not соврал,
                  '' if заметил and not соврал else 'скрипт отчитался об успехе — это Ф137')
    finally:
        shutil.rmtree(путь, ignore_errors=True)


def main():
    print('ПРОВЕРКИ ИНФРАСТРУКТУРЫ')
    print('=' * 70)
    проверка_автоотправки()
    проверка_гитигнора_картинок()
    проверка_транзита()
    try:
        import cv2  # noqa: F401
    except ImportError:
        отметка('сдача не проверена: нет библиотек — поставь automation/setup.sh', False)
    else:
        проверка_повторной_сдачи()
        проверка_архива()
    print('=' * 70)
    if сбои:
        print(f'УПАЛО: {len(сбои)} — ' + ', '.join(сбои))
        return 1
    print('ПРОШЛО — инфраструктура исправна')
    return 0


if __name__ == '__main__':
    sys.exit(main())
