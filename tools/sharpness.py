#!/usr/bin/env python3
"""Резкость вязки числом. Закрывает пункт опросника E1.

    python3 tools/sharpness.py кадр.png [кадр2.png …]
    python3 tools/sharpness.py --эталон принятый.png кадр.png

Зачем. Закон A6 стоит на числах «274 → 98 → 274»: фраза «полотно лежит гладко» обрушила
резкость вязки в 2.8 раза. Само число до 18.08 в комплекте посчитать было нечем — оно жило
в тексте закона, а инструмента не было (опросник E1). На глаз падение в два-три раза не
видно: заказчик замечает мыло раньше нас.

Что меряется. Дисперсия лапласиана по области изделия, приведённая к одной рабочей ширине
(иначе кадры разного размера несравнимы — та же ошибка, что чинилась в qc_frame, Ф17).
Область изделия берётся маской rembg: фон в кадре бывает резче полотна (ореховые доски),
и замер по всему кадру мерил бы стену.

Чего этот замер НЕ значит. Абсолютное число само по себе ничего не говорит: оно зависит от
изделия, плана и грейда. Смысл появляется только в сравнении с эталоном — принятым кадром
того же плана. Порога «хорошо/плохо» у скрипта нет.

**Калибровки у этой метрики нет, и это отрицательный результат, а не недоделка.** Первая
редакция обещала «уменьшение до 80% и 60% даёт 0.80× и 0.64×». Проверка на трёх кадрах:

    кадр          80%     60%     50%
    якорь        0.74×   1.16×   1.63×
    пэкшот       0.68×   0.92×   1.36×
    стена        0.51×   0.89×   1.26×

Второе число не сошлось ни разу, и зависимость **немонотонна**: на 50% отношение растёт выше
единицы. Дисперсия лапласиана зависит от размера принципиально — мельче пиксель, круче
перепад, — и приведением к общей ширине это не лечится (пробовал и «только вниз», и «всегда»:
разброс тот же). Прежние 0.80 и 0.64 были посчитаны на одном синтетическом кадре, и 0.64 —
это ровно 0.80², то есть арифметика, а не замер (Ф160).

**Что метрика ловит уверенно** — размытие при неизменном размере. Якорь против своих
размытых копий, гауссиан с указанной сигмой (числа воспроизводимы, в отличие от прежнего
«0.06×» без указания степени размытия):

    sigma 1.0 → 0.07×      sigma 2.0 → 0.01×      sigma 3.0 → 0.01×      ядро 9×9 → 0.02×

Уже при sigma 1.0 падение в четырнадцать раз, то есть глаз бы это увидел. Мягкое падение
резкости из закона A6 («в 2.8 раза») этой шкалой различимо, но на нашей серии не проверено:
пары «тот же кадр с фразой про гладкое полотно и без неё» в комплекте нет.

**Отсюда правило:** сравнивать можно только кадры **одинакового размера**, пиксель в пиксель.
Наши кадры приходят из сервиса одного разрешения, так что это выполнимо. Кадры разного
размера скрипт сравнивать отказывается — не предупреждает, а отказывается.
"""
import sys

import cv2
import numpy as np

WORK_W = 1600          # та же рабочая ширина, что у qc_frame
ПАДЕНИЕ = 0.50         # ниже половины эталона — почти наверняка мыло (A6: падение в 2.8 раза)


def работчая(im):
    k = WORK_W / im.shape[1]
    return cv2.resize(im, (WORK_W, int(im.shape[0] * k))) if k < 1 else im


def маска_изделия(path):
    """Маска человека с одеждой по rembg. None — если вырезать не удалось.

    Модель берётся из `scale_fig` — одна на комплект и названа явно. `try/except` здесь
    ловит не всё: если модель не влезает в память, процесс получает SIGKILL, и никакой
    откат «посчитаю по всему кадру» не сработает — питон просто умрёт (Ф159). Поэтому
    исправность вырезания проверяет `selftest` отдельным вызовом в дочернем процессе.
    """
    try:
        import os as _os
        import sys as _sys
        _sys.path.insert(0, _os.path.dirname(_os.path.abspath(__file__)))
        from rembg import remove
        from scale_fig import сессия_вырезания
        from PIL import Image
        import io
        вырез = remove(open(path, 'rb').read(), session=сессия_вырезания())
        a = np.array(Image.open(io.BytesIO(вырез)).convert('RGBA'))
        альфа = a[:, :, 3]
        return (альфа > 128).astype(np.uint8)
    except Exception:                                            # noqa: BLE001
        return None


def резкость(path):
    im = cv2.imread(path)
    if im is None:
        return None, 'файл не читается', None
    размер = (im.shape[1], im.shape[0])
    m = маска_изделия(path)
    im = работчая(im)
    серый = cv2.cvtColor(im, cv2.COLOR_BGR2GRAY)
    lap = cv2.Laplacian(серый, cv2.CV_64F)
    if m is not None:
        m = cv2.resize(m, (im.shape[1], im.shape[0]), interpolation=cv2.INTER_NEAREST)
        # Края маски дают ложную резкость: там перепад фигура/фон, а не петли.
        m = cv2.erode(m, np.ones((9, 9), np.uint8), iterations=1)
        если_есть = m.astype(bool)
        if если_есть.sum() < 5000:
            m, если_есть = None, None
    if m is None:
        return float(lap.var()), 'по всему кадру — фигуру вырезать не удалось', размер
    return float(lap[если_есть].var()), f'по изделию, {int(если_есть.sum() / 1000)}k точек', размер


def main():
    args = sys.argv[1:]
    if not args:
        print(__doc__.split('Зачем.')[0])
        return 2
    эталон = None
    if '--эталон' in args:
        i = args.index('--эталон')
        if i + 1 >= len(args):
            print('После --эталон не стоит файл.')
            return 2
        эталон = args[i + 1]
        args = args[:i] + args[i + 2:]
    if not args:
        print('Эталон есть, а кадров для сравнения нет.')
        return 2

    база = None
    if эталон:
        база, как, разм_эталона = резкость(эталон)
        if база is None:
            print(f'эталон не прочитан: {как}')
            return 2
        print(f"\nэталон: {эталон.split('/')[-1]}  резкость {база:.0f}  ({как})")

    print(f"\n{'кадр':<28}{'резкость':>10}{'к эталону':>11}  как считано")
    плохо = 0
    for p in args:
        v, как, разм = резкость(p)
        if v is None:
            print(f"{p.split('/')[-1]:<28}{'—':>10}{'—':>11}  {как}")
            continue
        отн = f'{v / база:.2f}×' if база else '—'
        метка = ''
        # Метрика не инвариантна к размеру: тот же кадр, уменьшенный до 80% и 60%, даёт
        # 0.80× и 0.64×. Сравнивать можно только кадры одной ширины оригинала — иначе
        # число мерит разрешение, а не вязку (та же болезнь, что чинилась в Ф17).
        if база and разм_эталона and разм and разм != разм_эталона:
            метка = (f'  ← {разм[0]}×{разм[1]} против {разм_эталона[0]}×{разм_эталона[1]} '
                     'у эталона: числа несравнимы, сравнение не выполнено')
            отн = '—'
            плохо += 1
        elif база and v / база < ПАДЕНИЕ:
            метка = '  ← падение больше чем вдвое, смотреть глазами'
            плохо += 1
        print(f"{p.split('/')[-1]:<28}{v:>10.0f}{отн:>11}  {как}{метка}")
    print('\nЧисло сравнимо только с эталоном того же плана и ТОГО ЖЕ РАЗМЕРА, пиксель в')
    print('пиксель. Калибровки у метрики нет: отношение при уменьшении кадра ведёт себя')
    print('немонотонно и на 50% уходит выше единицы. Порога «хорошо» здесь тоже нет —')
    print('метрика без внешней калибровки не может быть критерием остановки (закон F1).\n')
    return 1 if плохо else 0


if __name__ == '__main__':
    sys.exit(main())
